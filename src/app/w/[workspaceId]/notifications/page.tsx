import type { Metadata } from "next";
import { revalidatePath } from "next/cache";
import Link from "next/link";
import { LocalTime } from "@/components/local-time";
import { EmptyState, PageHeader } from "@/components/ui";
import { getWebCtx } from "@/server/db/web";
import { listNotifications, markAllRead } from "@/server/modules/notifications/service";

export const metadata: Metadata = { title: "Alerts" };

export default async function NotificationsPage({ params }: { params: Promise<{ workspaceId: string }> }) {
  const { workspaceId } = await params;
  const ctx = await getWebCtx();
  const notifications = await listNotifications(ctx, workspaceId);
  const unread = notifications.filter((n) => !n.read_at).length;

  async function markRead() {
    "use server";
    await markAllRead(await getWebCtx(), workspaceId);
    revalidatePath(`/w/${workspaceId}`, "layout");
  }

  return (
    <div className="max-w-2xl">
      <PageHeader title="Alerts">
        {unread > 0 && (
          <form action={markRead}>
            <button className="btn" type="submit">Mark all as read</button>
          </form>
        )}
      </PageHeader>
      {notifications.length === 0 ? (
        <EmptyState icon="bell" title="No alerts" body="You will see a message here when someone gives you a task, comments on one of yours, or decides on time off." />
      ) : (
        <section className="card">
          <ul>
            {notifications.map((n) => (
              <li key={n.id} className="row">
                <span className={`h-2.5 w-2.5 shrink-0 rounded-full ${n.read_at ? "bg-transparent" : "bg-accent"}`} aria-hidden="true" />
                <div className={`min-w-0 flex-1 ${n.read_at ? "text-muted" : "font-medium"}`}>
                  {!n.read_at && <span className="sr-only">New: </span>}
                  {/* Links are generated by database triggers and always point inside this app. */}
                  {n.link?.startsWith("/w/") ? <Link className="hover:underline" href={n.link}>{n.title}</Link> : n.title}
                  <div className="muted font-normal"><LocalTime iso={n.created_at} /></div>
                </div>
              </li>
            ))}
          </ul>
        </section>
      )}
    </div>
  );
}
